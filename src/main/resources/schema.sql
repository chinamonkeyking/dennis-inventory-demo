-- Demo-only schema initialization.
-- spring.sql.init.mode=always reruns these scripts on every Spring context start, while
-- DB_CLOSE_DELAY=-1 keeps the in-memory database alive across context restarts in the same JVM.
-- Drop first so repeated runs, tests, and DevTools restarts always begin from a clean state.
-- Never use this drop/create approach for a persistent production database.
DROP TABLE IF EXISTS inventory;
DROP TABLE IF EXISTS category;

CREATE TABLE category (
    id INT PRIMARY KEY,
    parent_id INT NULL,
    name VARCHAR(255) NOT NULL,
    version INT NOT NULL DEFAULT 0,
    created_by VARCHAR(255) NOT NULL,
    created_at_utc_ms BIGINT NOT NULL,
    updated_by VARCHAR(255) NULL,
    updated_at_utc_ms BIGINT NULL,
    CONSTRAINT uk_category_name UNIQUE (name),
    CONSTRAINT fk_category_parent FOREIGN KEY (parent_id) REFERENCES category (id)
);

CREATE TABLE inventory (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    category_id INT NOT NULL,
    sub_category_id INT NOT NULL,
    quantity INT NOT NULL,
    version INT NOT NULL DEFAULT 0,
    created_by VARCHAR(255) NOT NULL,
    created_at_utc_ms BIGINT NOT NULL,
    updated_by VARCHAR(255) NULL,
    updated_at_utc_ms BIGINT NULL,
    CONSTRAINT uk_inventory_name UNIQUE (name),
    CONSTRAINT fk_inventory_category FOREIGN KEY (category_id) REFERENCES category (id),
    CONSTRAINT fk_inventory_sub_category FOREIGN KEY (sub_category_id) REFERENCES category (id),
    CONSTRAINT ck_inventory_quantity_non_negative CHECK (quantity >= 0)
);
